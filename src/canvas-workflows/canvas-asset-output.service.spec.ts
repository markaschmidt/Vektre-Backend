import type { AppDataService } from '../integrations/app-data.service.js';
import type { SupabaseService } from '../integrations/supabase.js';
import type { StorageQuotaService } from '../storage-quota/storage-quota.service.js';
import { CanvasAssetOutputService } from './canvas-asset-output.service.js';
import type { UiContextIndexQueue } from '../ui-agent/indexer/ui-context-index.queue.js';

describe('CanvasAssetOutputService', () => {
  it('checks storage quota before materializing generated bytes', async () => {
    const appData = {
      upsertProjectAsset: jest.fn(),
      updateProjectAssetStatus: jest.fn(),
    };
    const supabase = {
      getStorageBucket: jest.fn().mockReturnValue('project-assets'),
      uploadObject: jest.fn(),
    };
    const storageQuota = {
      assertWithinQuota: jest.fn(),
    };
    const contextIndexQueue = {
      enqueueAsset: jest.fn().mockResolvedValue(true),
    };
    const service = new CanvasAssetOutputService(
      appData as unknown as AppDataService,
      supabase as unknown as SupabaseService,
      storageQuota as unknown as StorageQuotaService,
      contextIndexQueue as unknown as UiContextIndexQueue,
    );

    await service.materializeBytes({
      projectId: 'project-1',
      userId: 'user-1',
      assetId: 'asset-1',
      assetType: 'image',
      name: 'output.png',
      mimeType: 'image/png',
      bytes: Buffer.from('image-bytes'),
    });

    expect(storageQuota.assertWithinQuota).toHaveBeenCalledWith(
      'user-1',
      'project-1',
      11,
      'asset-1',
    );
    expect(
      storageQuota.assertWithinQuota.mock.invocationCallOrder[0],
    ).toBeLessThan(appData.upsertProjectAsset.mock.invocationCallOrder[0]);
  });
});
